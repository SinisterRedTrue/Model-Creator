'use strict';

const path = require('path');
const versions = require('./versions');
const briefLib = require('./brief');
const texture = require('./texture');
const render = require('./render');
const { javaToBbmodel } = require('./bbmodel');
const { loadModel, modelFile } = require('./model');
const { ensureDir, writeJson, writeText, exists, rel, usage, slug } = require('./util');

const HANDHELD = /(_sword|_axe|_pickaxe|_shovel|_hoe)$|^(stick|blaze_rod|breeze_rod|bone|mace|trident)$/;

function title(name) {
  return String(name).replace(/[_.-]+/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());
}

function baseName(id) {
  return String(id || '').replace(/^minecraft:/, '');
}

// Wire the custom model to a base item for the target version.
function itemWiring(packDir, info, ns, name, folder, base, cmd, type) {
  const files = [];
  const modelId = `${ns}:${folder}/${name}`;
  if (info.item_definitions) {
    files.push(writeOut(path.join(packDir, 'assets', ns, 'items', `${name}.json`), {
      model: { type: 'minecraft:model', model: modelId },
    }));
  }
  if (!base) return files;
  if (type === 'block') {
    files.push(writeOut(path.join(packDir, 'assets', 'minecraft', 'blockstates', `${base}.json`), {
      variants: { '': { model: modelId } },
    }));
    return files;
  }
  if (info.item_definitions) {
    files.push(writeOut(path.join(packDir, 'assets', 'minecraft', 'items', `${base}.json`), {
      model: {
        type: 'minecraft:range_dispatch',
        property: 'minecraft:custom_model_data',
        index: 0,
        entries: [{ threshold: cmd, model: { type: 'minecraft:model', model: modelId } }],
        fallback: { type: 'minecraft:model', model: `minecraft:item/${base}` },
      },
    }));
  } else {
    files.push(writeOut(path.join(packDir, 'assets', 'minecraft', 'models', 'item', `${base}.json`), {
      parent: HANDHELD.test(base) ? 'minecraft:item/handheld' : 'minecraft:item/generated',
      textures: { layer0: `minecraft:item/${base}` },
      overrides: [{ predicate: { custom_model_data: cmd }, model: modelId }],
    }));
  }
  return files;
}

function writeOut(file, json) {
  writeJson(file, json);
  return file;
}

// Plugin and mod targets. Unsupported parts are returned as manual steps.
function deliveryFiles(packDir, brief, info) {
  const s = brief.spec;
  const ns = brief.namespace;
  const name = brief.name;
  const base = baseName(s.base_item) || 'paper';
  const material = base.toUpperCase();
  const outRoot = path.join(packDir, '..', `${path.basename(packDir)}.${s.delivery}`);
  const files = [];
  const manual = [];
  const header = '# Generated by Model Creator. Check keys against your plugin version before use.\n';
  switch (s.delivery) {
    case 'itemsadder':
      files.push(writeTextOut(path.join(outRoot, 'contents', ns, 'configs', `${name}.yml`),
        `${header}info:\n  namespace: ${ns}\nitems:\n  ${name}:\n    display_name: "${title(name)}"\n    resource:\n      material: ${material}\n      generate: false\n      model_path: item/${name}\n`));
      manual.push(`Copy ${rel(path.join(packDir, 'assets', ns))} to plugins/ItemsAdder/contents/${ns}/resourcepack/assets/${ns}`);
      manual.push(`Copy ${rel(path.join(outRoot, 'contents', ns, 'configs'))} to plugins/ItemsAdder/contents/${ns}/configs, then run /iazip`);
      break;
    case 'oraxen':
      files.push(writeTextOut(path.join(outRoot, 'items', `${name}.yml`),
        `${header}${name}:\n  displayname: "<white>${title(name)}"\n  material: ${material}\n  Pack:\n    generate_model: false\n    model: ${ns}/item/${name}\n`));
      manual.push(`Copy ${rel(path.join(packDir, 'assets'))} into plugins/Oraxen/pack/assets`);
      manual.push(`Copy ${rel(path.join(outRoot, 'items', `${name}.yml`))} into plugins/Oraxen/items, then run /oraxen reload all`);
      break;
    case 'nexo':
      files.push(writeTextOut(path.join(outRoot, 'items', `${name}.yml`),
        `${header}${name}:\n  itemname: "<white>${title(name)}"\n  material: ${material}\n  Pack:\n    model: ${ns}:item/${name}\n`));
      manual.push(`Copy ${rel(path.join(packDir, 'assets'))} into plugins/Nexo/pack/assets`);
      manual.push(`Copy ${rel(path.join(outRoot, 'items', `${name}.yml`))} into plugins/Nexo/items, then run /nexo reload all`);
      break;
    case 'modelengine': {
      const m = loadModel(modelFile(packDir, `${ns}:${briefLib.folderOf(brief)}/${name}`), { root: packDir });
      const groups = [];
      let idx = 0;
      for (const p of brief.parts) {
        const n = p.elements.length;
        groups.push({ name: p.name, origin: p.pivot || [8, 0, 8], elements: Array.from({ length: n }, (_, k) => idx + k) });
        idx += n;
      }
      const bb = javaToBbmodel(m, { name, groups, format: 'free' });
      files.push(writeOut(path.join(outRoot, `${name}.bbmodel`), bb));
      manual.push(`Copy ${rel(path.join(outRoot, `${name}.bbmodel`))} to plugins/ModelEngine/blueprints, then run /meg reload`);
      manual.push('Add hitbox and mount/seat bones in Blockbench if the model needs them');
      break;
    }
    case 'fabric':
    case 'forge':
      manual.push(`Copy ${rel(path.join(packDir, 'assets', ns))} to src/main/resources/assets/${ns} in your mod`);
      manual.push(`Register an item with id ${ns}:${name}; the game loads ${info.item_definitions ? `assets/${ns}/items/${name}.json` : `assets/${ns}/models/item/${name}.json`} for it`);
      break;
    default:
      break;
  }
  return { files, manual };
}

function writeTextOut(file, text) {
  writeText(file, text);
  return file;
}

function run(dir, opts = {}) {
  if (!dir) throw usage('scaffold needs an output directory');
  const packDir = path.resolve(dir);
  let brief = null;
  let baseDir = process.cwd();
  if (opts.brief) {
    brief = briefLib.load(opts.brief);
    baseDir = path.dirname(path.resolve(opts.brief));
    const problems = briefLib.check(brief, { baseDir }).filter((p) => p.level === 'error');
    if (problems.length) {
      const err = usage(`brief is invalid; run "mcmodel brief check" first:\n${problems.map((p) => `${p.path}: ${p.message}`).join('\n')}`);
      err.code = 1;
      throw err;
    }
  }
  const s = brief ? brief.spec : {};
  const version = opts.version || s.minecraft_version;
  if (!version) throw usage('scaffold needs --version (or --brief)');
  const info = versions.get(version);
  const ns = opts.namespace || (brief && brief.namespace) || 'custom';
  if (!/^[a-z0-9_.-]+$/.test(ns)) throw usage(`namespace "${ns}" must match [a-z0-9_.-]+`);
  const delivery = opts.delivery || s.delivery || 'vanilla';
  const name = brief ? brief.name : slug(opts.name || 'model');
  const files = [];
  const manual = [];

  files.push(writeOut(path.join(packDir, 'pack.mcmeta'), {
    pack: { pack_format: info.resource_pack_format, description: `${title(name)} - made with Model Creator` },
  }));
  for (const f of ['block', 'item']) {
    ensureDir(path.join(packDir, 'assets', ns, 'models', f));
    ensureDir(path.join(packDir, 'assets', ns, 'textures', f));
  }

  let give = null;
  if (brief) {
    files.push(...texture.fromBrief(brief, packDir, baseDir));
    const folder = briefLib.folderOf(brief);
    const modelJson = briefLib.toModel(brief);
    const mf = modelFile(packDir, `${ns}:${folder}/${name}`);
    if (exists(mf) && !opts.force) {
      manual.push(`${rel(mf)} already existed and was kept; pass --force to regenerate it from the brief`);
    } else {
      files.push(writeOut(mf, modelJson));
    }
    const base = baseName(s.base_item);
    const cmd = s.custom_model_data || 1;
    if (delivery === 'vanilla' || delivery === 'fabric' || delivery === 'forge') {
      files.push(...itemWiring(packDir, info, ns, name, folder, delivery === 'vanilla' ? base : null, cmd, s.model_type));
      if (delivery === 'vanilla' && base && s.model_type !== 'block') give = info.give.replace('{base}', base).replace('{cmd}', cmd);
      if (delivery === 'vanilla' && s.model_type === 'block' && base) {
        manual.push(`assets/minecraft/blockstates/${base}.json replaces every ${base} block; blocks with states (stairs, slabs, doors) need each variant mapped by hand`);
      }
      if (info.item_model_component && delivery === 'vanilla') {
        const alt = `/give @s minecraft:${base || 'paper'}[minecraft:item_model="${ns}:${name}"]`;
        give = give ? `${give}\n${alt}` : alt;
      }
    } else if (info.item_definitions) {
      files.push(...itemWiring(packDir, info, ns, name, folder, null, cmd, s.model_type));
    }
    const d = deliveryFiles(packDir, brief, info);
    files.push(...d.files);
    manual.push(...d.manual);
    // pack.png icon from an isometric render.
    try {
      const m = loadModel(mf, { root: packDir });
      const icon = render.renderQuads(render.quadsForModel(m), Object.assign({ size: 128 }, render.VIEWS.iso));
      files.push(icon.save(path.join(packDir, 'pack.png')));
    } catch (err) {
      manual.push(`pack.png not generated: ${err.message}`);
    }
  }
  return { pack: rel(packDir), version: info.version, pack_format: info.resource_pack_format, namespace: ns, delivery, files: files.map((f) => rel(f)), give, manual_steps: manual };
}

module.exports = { run, itemWiring, HANDHELD, title };
